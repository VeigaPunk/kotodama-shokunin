TAMPER_LINE = "\n# TAMPER-PROBE neg-13 (must never be silently erased)\n"


def sha256(path):
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def mtime_ns(path):
    return os.stat(path).st_mtime_ns


def run_selftest(gates_dir, gate, timeout=180):
    proc = subprocess.run(
        [sys.executable, os.path.join(gates_dir, gate), "--selftest"],
        cwd=gates_dir, capture_output=True, text=True, timeout=timeout)
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def new_scratch(gates_dir, tmp_root):
    """Fresh private copy of the gates tree; never the live tree."""
    dest = os.path.join(tempfile.mkdtemp(dir=tmp_root), "gates")
    shutil.copytree(gates_dir, dest,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    return dest


def materialize_from_git(rev, tmp):
    dest = os.path.join(tmp, "git-%s" % rev.replace("/", "_"))
    os.makedirs(dest, exist_ok=True)
    proc = subprocess.Popen(["git", "-C", REPO, "archive", rev, "tools/gates"],
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    with tarfile.open(fileobj=proc.stdout, mode="r|") as tar:
        try:
            tar.extractall(path=dest, filter="data")
        except TypeError:  # Python < 3.12
            tar.extractall(path=dest)
    stderr = proc.stderr.read().decode("utf-8", "replace")
    if proc.wait() != 0:
        raise SystemExit("NEG-13 ERROR: git archive %s failed: %s" % (rev, stderr))
    return os.path.join(dest, "tools", "gates")


def check_clean(gates_dir, gate, files, tmp_root):
    """Post-fix: selftest exits 0 and writes nothing (bytes AND mtimes)."""
    scratch = new_scratch(gates_dir, tmp_root)
    before = {f: (sha256(os.path.join(scratch, f)), mtime_ns(os.path.join(scratch, f)))
              for f in files}
    rc, out = run_selftest(scratch, gate)
    after = {f: (sha256(os.path.join(scratch, f)), mtime_ns(os.path.join(scratch, f)))
             for f in files}
    if rc != 0:
        return "clean run exited %s, expected 0; output=%r" % (rc, out.strip()[-200:])
    for f in files:
        if before[f][0] != after[f][0]:
            return "clean run changed fixture bytes: %s" % f
        if before[f][1] != after[f][1]:
            return ("PRE-FIX PATTERN OBSERVED: clean run rewrote %s in place "
                    "(mtime changed; truncating write)" % f)
    return None


def check_tamper(gates_dir, gate, files, tmp_root):
    """Post-fix: tampered fixture is refused loudly and never overwritten."""
    scratch = new_scratch(gates_dir, tmp_root)
    original = {f: sha256(os.path.join(scratch, f)) for f in files}
    tampered = {}
    for f in files:
        path = os.path.join(scratch, f)
        with open(path, "a", encoding="utf-8") as handle:
            handle.write(TAMPER_LINE)
        tampered[f] = sha256(path)
    rc, out = run_selftest(scratch, gate)
    restored = [f for f in files if sha256(os.path.join(scratch, f)) == original[f]]
    preserved = [f for f in files if sha256(os.path.join(scratch, f)) == tampered[f]]
    if rc == 0 and restored:
        return ("PRE-FIX PATTERN OBSERVED: tampered %s silently erased "
                "(exit 0, original bytes restored): %s" % (restored[0], out.strip()[-160:]))
    if rc == 0:
        return "tamper accepted with exit 0 and no diagnostic: %r" % out.strip()[-160:]
    if "Traceback (most recent call last)" in out:
        return "tamper rejected with a crash traceback instead of a stable diagnostic"
    if "SELFTEST FAIL" not in out:
        return "tamper rejected without a stable 'SELFTEST FAIL' diagnostic: %r" % out.strip()[-160:]
    if len(preserved) != len(files):
        lost = [f for f in files if f not in preserved]
        return "tampered bytes were modified despite rejection: %s" % lost
    return None


def check_absent(gates_dir, gate, primary, tmp_root):
    """Post-fix: a missing fixture is regenerated atomically and identically."""
    scratch = new_scratch(gates_dir, tmp_root)
    path = os.path.join(scratch, primary)
    original = sha256(path)
    os.unlink(path)
    rc, out = run_selftest(scratch, gate)
    if rc != 0:
        return "absent-fixture run exited %s, expected 0; output=%r" % (rc, out.strip()[-200:])
    if not os.path.exists(path):
        return "absent fixture %s was not regenerated" % primary
    if sha256(path) != original:
        return "regenerated %s differs from the committed bytes" % primary
    leftovers = [name for name in os.listdir(os.path.dirname(path))
                 if ".tmp-" in name]
    if leftovers:
        return "regeneration left temp files behind: %s" % leftovers
    return None


def check_reader_tamper(gates_dir, gate, fixture, expected, tmp_root):
    """Boundary control: the two reader gates still fail loudly on tamper."""
    scratch = new_scratch(gates_dir, tmp_root)
    for f in (fixture, expected):
        with open(os.path.join(scratch, f), "a", encoding="utf-8") as handle:
            handle.write(TAMPER_LINE)
    rc, out = run_selftest(scratch, gate)
    if rc == 0:
        return ("reader-gate boundary broken: tampered %s selftest exited 0; "
                "output=%r" % (fixture, out.strip()[-160:]))
    return None


def make_scratch_root(explicit=None):
    """Scratch root with the most free space among the writable candidates.

    The fleet runs many workers in parallel and the default system temp dir
    can fill up mid-run (observed: ENOSPC during this control's own
    development), so an explicit ``--scratch-root`` or ``NEG13_SCRATCH_DIR``
    overrides the choice and the candidates are ranked by free bytes.
    """
    candidates = [explicit, os.environ.get("NEG13_SCRATCH_DIR"),
                  tempfile.gettempdir(), "/var/tmp", "/tmp"]
    best = None
    for base in candidates:
        if not base or not os.path.isdir(base):
            continue
        try:
            stat = os.statvfs(base)
        except OSError:
            continue
        free = stat.f_bavail * stat.f_frsize
        if best is None or free > best[1]:
            best = (base, free)
    if best is None:
        raise SystemExit("NEG-13 ERROR: no writable scratch root")
    return tempfile.mkdtemp(prefix="neg-13-", dir=best[0])


def main():
    parser = argparse.ArgumentParser(
        description="Negative control for round-8 defect R8-O13 (review 29 F1).",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--gates-dir", default=None,
                        help="gates tree to test (default: the live repo tools/gates)")
    parser.add_argument("--from-git", metavar="REV", default=None,
                        help="materialize tools/gates from git revision REV and test that copy")
    parser.add_argument("--scratch-root", default=None,
                        help="directory for scratch copies (default: most free of "
                             "NEG13_SCRATCH_DIR, system temp, /var/tmp, /tmp)")
    args = parser.parse_args()

    tmp_root = make_scratch_root(args.scratch_root)
    print("NEG-13 scratch root: %s" % tmp_root)
    failures = []
    checks = 0
    try:
        if args.from_git:
            gates_dir = materialize_from_git(args.from_git, tmp_root)
            print("NEG-13 gates source: git revision %s (git archive)" % args.from_git)
        elif args.gates_dir:
            gates_dir = os.path.abspath(args.gates_dir)
            print("NEG-13 gates source: %s" % gates_dir)
        else:
            gates_dir = DEFAULT_GATES_DIR
            print("NEG-13 gates source: live tree %s" % gates_dir)
        if not os.path.isdir(gates_dir):
            print("NEG-13 ERROR: gates dir not found: %s" % gates_dir)
            return 2

        for gate, _, _ in WRITER_GATES + READER_GATES:
            path = os.path.join(gates_dir, gate)
            if not os.path.isfile(path):
                print("NEG-13 ERROR: gate not found: %s" % path)
                return 2
            digest = sha256(path)
            if PRE_FIX_SHA256.get(gate) == digest \
                    and any(gate == w[0] for w in WRITER_GATES):
                note = " (pre-fix writer pin: tamper checks expected to FAIL)"
            else:
                note = ""
            print("NEG-13 gate %-32s sha256=%s%s" % (gate, digest[:16], note))

        def record(name, result):
            nonlocal checks
            checks += 1
            print("NEG-13 %-38s %s" % (name, "PASS" if result is None else "FAIL"))
            if result is not None:
                failures.append("%s: %s" % (name, result))

        for gate, primary, files in WRITER_GATES:
            record("%s clean-writes-nothing" % gate.replace(".py", ""),
                   check_clean(gates_dir, gate, files, tmp_root))
            record("%s tamper-refused-preserved" % gate.replace(".py", ""),
                   check_tamper(gates_dir, gate, files, tmp_root))
            record("%s absent-regenerated" % gate.replace(".py", ""),
                   check_absent(gates_dir, gate, primary, tmp_root))
        for gate, fixture, expected in READER_GATES:
            record("%s reader-tamper-loud" % gate.replace(".py", ""),
                   check_reader_tamper(gates_dir, gate, fixture, expected, tmp_root))
    finally:
        shutil.rmtree(tmp_root, ignore_errors=True)

    if failures:
        print("NEG-13 RESULT: FAIL (%d/%d checks)" % (len(failures), checks))
        for line in failures:
            print("NEG-13 FAILURE: %s" % line)
        return 1
    print("NEG-13 RESULT: PASS (%d/%d checks)" % (checks, checks))
    return 0


if __name__ == "__main__":
    sys.exit(main())
